const assert=require('node:assert/strict'),P=require('./map-physics.cjs');
const m={width:12,height:10,layers:{ground:Array(120).fill('grassland'),collision:Array(120).fill(0),objects:[{id:'box',x:4,y:4,kind:'木箱'},{id:'tree',x:7,y:4,kind:'阔叶树'}]}};
for(let y=2;y<=7;y++)m.layers.ground[y*12+9]='water';P.attach(m);
assert.equal(P.attempt(m,{x:3.5,y:4.5,z:0},{x:4.5,y:4.5},'walk').ok,false);
const atop=P.attempt(m,{x:3.5,y:4.5,z:0},{x:4.5,y:4.5},'jump');assert.equal(atop.ok,true);assert.equal(atop.player.z,.8);assert.equal(atop.player.platform,'box');
assert.equal(P.attempt(m,atop.player,{x:4.55,y:4.5},'walk').ok,true);
assert.equal(P.attempt(m,atop.player,{x:5.5,y:4.5},'walk').ok,true);
assert.equal(P.attempt(m,{x:6.5,y:4.5,z:0},{x:7.5,y:4.5},'walk').ok,false);
assert.equal(P.attempt(m,{x:6.5,y:4.5,z:0},{x:8.5,y:4.5},'jump').ok,false);
assert.equal(P.attempt(m,{x:8.5,y:4.5,z:0},{x:9.5,y:4.5},'walk').ok,false);
assert.equal(P.attempt(m,{x:8.5,y:4.5,z:0},{x:10.5,y:4.5},'walk').ok,false);
assert.equal(P.attempt(m,{x:8.5,y:4.5,z:0},{x:9.5,y:4.5},'jump').ok,false);
assert.equal(P.attempt(m,{x:8.5,y:4.5,z:0},{x:10.5,y:4.5},'jump').ok,true);
assert.equal(P.attempt(m,{x:2.5,y:2.5,z:0},{x:8.5,y:2.5},'jump').ok,false);
assert.equal(P.attempt(m,{x:3.5,y:4.5,z:0},{x:5.5,y:4.5},'walk').ok,false);
assert.equal(P.attempt(m,{x:NaN,y:4},{x:4,y:4}).ok,false);
assert.equal(P.attempt(m,{x:3.5,y:4.5,z:0},{x:4.5,y:4.5},'teleport').ok,false);
let peak=0;for(let i=0;i<=1000;i++)peak=Math.max(peak,P.jumpZ(0,.8,i/1000));assert.ok(peak<=P.DEFAULT.maxJumpRise+1e-6);
const bad=JSON.parse(JSON.stringify(m));bad.physics.surfaces[0].depth=-1;assert.throws(()=>P.validate(bad));
console.log('PASS: tree collision, no walking/landing on water, narrow-water jump, box jump/top support/walk-off, swept collision and jump range.');
